def placeholders(s):
    seen = []
    for m in re.findall(r'\{(\w+)\}', s):
        if m not in seen: seen.append(m)
    return seen

# validation: same placeholders in every language
problems = []
for k, vals in S.items():
    ph = placeholders(vals[0])
    for i, v in enumerate(vals):
        if placeholders(v) != ph and set(placeholders(v)) != set(ph):
            problems.append((k, LANGS[i], placeholders(v), ph))
        if not v.strip(): problems.append((k, LANGS[i], 'empty'))
if problems:
    print('PROBLEMS'); [print(' ', p) for p in problems]; sys.exit(1)

# web: JSON
web = {l: {k: v[i] for k, v in S.items()} for i, l in enumerate(LANGS)}
json.dump(web, open(os.path.join(ROOT, 'strings.json'), 'w'), ensure_ascii=False, indent=1)

def xml_escape(s):
    s = s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    s = s.replace("'", "\\'").replace('"', '\\"')
    if s.startswith('@') or s.startswith('?'): s = '\\' + s
    return s

def android_text(s, key):
    ph = placeholders(S[key][0])
    out = s
    for idx, name in enumerate(ph, 1):
        out = out.replace('{' + name + '}', '%' + str(idx) + '$s')
    out = out.replace('%', '%%') if not ph and '%' in out else out
    if ph:
        # escape stray % that are not our placeholders
        out = re.sub(r'%(?!\d\$s)', '%%', out)
    return xml_escape(out)

